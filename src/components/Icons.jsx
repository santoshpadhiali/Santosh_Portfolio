export const DynamicIcon = ({ name, className = "w-5 h-5" }) => {
  switch (name?.toLowerCase()) {
    case 'code':
      return <IconCode className={className} />;
    case 'server':
      return <IconServer className={className} />;
    case 'database':
      return <IconDatabase className={className} />;
    case 'cpu':
      return <IconCpu className={className} />;
    case 'terminal':
      return <IconTerminal className={className} />;
    case 'github':
      return <IconGithub className={className} />;
    case 'mail':
      return <IconMail className={className} />;
    case 'phone':
      return <IconPhone className={className} />;
    case 'whatsapp':
      return <IconWhatsapp className={className} />;
    case 'graduation':
    case 'graduationcap':
      return <IconGraduationCap className={className} />;
    case 'calendar':
      return <IconCalendar className={className} />;
    case 'award':
      return <IconAward className={className} />;
    case 'briefcase':
      return <IconBriefcase className={className} />;
    default:
      return <IconSparkles className={className} />;
  }
};

